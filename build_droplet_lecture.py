# ====================================================== 3 称重 =============
b.h1("3　称重平均法：基准方法", "Gravimetric Averaging: the Reference Method",
     page_break_before=True)
b.h2("3.1　做法与可行性", "Procedure and Feasibility")
b.para("用接液杯收集 N 滴，在分析天平上称收集前后的质量差，除以滴数：")
b.equation("m̄ = ( M_{2} − M_{1} ) / N，　N = f·t（或直接计驱动脉冲数）", "3.1")
b.para("平均单滴质量的分辨率由天平分辨率摊薄决定：", indent=False)
b.equation("σ_{rel} = Δm_{天平} / ( m̄·N )", "3.2")
b.para("在 450 滴/秒下“攒滴数”极快：图 2 显示，100 μm 液滴配 0.01 mg 半微量天平，"
       "约 40 秒即可把平均值分辨率做到 0.1%；即使 50 μm 的小滴（单滴仅 65 ng），"
       "几百秒也能达到。滴数不必人工数——喷射阀一个驱动脉冲一滴，直接计脉冲；"
       "非同步产生的滴用光电对射计数。", indent=False)
b.figure(f"{F}/fd2_gravimetric.png", "2",
         "称重平均法可行性：分辨率随采集时间的变化",
         "Gravimetric feasibility: resolution vs. collection time", 15.5)
b.h2("3.2　误差源与对策", "Error Sources")
b.bullet("蒸发（最主要）：接液杯预放一层低挥发硅油覆盖液面；或单独测“蒸发速率空白”"
         "（不喷液称杯子质量随时间的变化）做修正；挥发性溶剂必要时加饱和蒸汽罩。")
b.bullet("静电：喷射液滴常带电，会粘杯壁、偏飞甚至排斥逃逸；用离子风机中和，"
         "接液杯接地。")
b.bullet("气流与振动：天平防风罩必须关闭；接液与称重分开进行（收集完再上天平）。")
b.bullet("飞溅与挂壁：杯口足够大、杯内预置液层减小溅出；喷嘴到杯的路径加防护套管。")
b.bullet("计数口径：卫星滴（主滴后的小尾滴）算不算一滴？要与成像观察对齐口径，"
         "否则平均值有系统偏差。")

# ====================================================== 4 成像 =============
b.h1("4　频闪成像法：逐滴体积", "Strobe Imaging: Per-drop Volume")
b.para("即喷墨行业的 drop watcher 原理：LED 纳秒频闪与滴发生器同步，相机拍摄飞行中的"
       "液滴，图像测直径换算体积与质量：")
b.equation("m = ρ·(π/6)·d^{3}，　δm/m = 3·δd/d + δρ/ρ", "4.1")
b.para("400~500 滴/秒对该方法毫无压力（喷墨行业在几十 kHz 下常规使用）；扫描频闪延时"
       "还能沿飞行方向“慢放”整个断裂-收缩过程，观察卫星滴与断尾。", indent=False)
b.para("实施要点：")
b.bullet("直径误差被三次方放大：1% 的直径误差就是 3% 的质量误差——用远心镜头消除"
         "透视误差，标定用标准刻度片，边缘检测取灰度重心而非阈值。")
b.bullet("在液滴收缩为球形之后再测（离喷口/断裂点足够远），非球形帧不能按球算。")
b.bullet("卫星滴单独计量：主滴 + 卫星滴的总体积才对应称重法的“一滴”。")
b.bullet("密度要按实际温度取值；含气泡的液体密度不确定度会直接进入结果。")
b.para("成像法与称重法互补：称重给准确的平均值，成像给逐滴散布——两者对不上时，"
       "通常是卫星滴口径或蒸发出了问题。")

# ====================================================== 5 偏转 =============
b.h1("5　电场偏转法：由偏移量反算质量（重点分析）",
     "Electrostatic Deflection: Mass from Trajectory Deflection",
     page_break_before=True)
b.para("思路：让液滴带上电荷 q，横穿一段匀强电场 E，测量它在检测面上的横向偏移量 y，"
       "由偏移反算质量。这正是密立根油滴实验与连续喷墨（CIJ）打印机偏转系统的物理。"
       "本章先给公式，再用数值仿真回答三个问题：偏移量有多大（可测吗）、简化公式误差"
       "多大（怎么修正）、总精度多少（值不值得做）。")

b.h2("5.1　原理与公式：测到的是荷质比，不是质量", "It Measures q/m, not m")
b.para("装置示意见图 3：喷嘴竖直向下喷射，感应充电电极在射流断裂成滴的瞬间给滴充电 q；"
       "液滴以速度 v 进入长度 L 的偏转板区，受横向力 qE；在距离 D 的检测面上测偏移 y。"
       "忽略空气阻力的简化公式为：")
b.equation("y = ( q·E·L / m·v^{2} )·( D − L/2 )", "5.1")
b.figure(f"{F}/fd3_rig.png", "3",
         "电场偏转法测量装置示意（轨迹为含阻力仿真结果）",
         "Electrostatic deflection rig (trajectory from drag-included "
         "simulation)", 14.5)
b.para("注意式 5.1 中 q 与 m 永远以比值形式出现——偏移量测的是荷质比 q/m。要得到质量，"
       "必须把 q、v、E、y 全部独立测出后反解：")
b.equation("m = q·E·L·( D − L/2 ) / ( v^{2}·y )", "5.2")
b.bullet("电荷 q：用法拉第杯接住液滴串、皮安表测电流，I = q·f（式 5.3）。例如 0.3 pC × "
         "450 Hz ≈ 0.14 nA，可测；但这给出的是平均电荷，滴间散布直接进入质量误差。")
b.equation("I = q·f", "5.3")
b.bullet("速度 v：双脉冲频闪成像或双光幕测轴向速度；注意 v 以平方进入公式，"
         "速度误差对结果翻倍。")
b.bullet("偏移 y：相机或位置敏感探测器（PSD）测量。")

b.h2("5.2　电荷从哪里来、能充多大", "Charging Physics and Limits")
b.para("感应充电：在射流断裂点附近放置充电电极并加电压，导电液体中的自由电荷在断裂瞬间"
       "被“冻结”在滴上。这要求液体有足够电导率（水基液体通常 >50~100 μS/cm 即可）；"
       "液压油、溶剂等介电液体感应充电几乎无效、电荷量不稳定——这条路的第一个前提就是"
       "液体导电。充电量的物理上限是 Rayleigh 极限（超过后库仑斥力撕裂液滴）：")
b.equation("q_{R} = 8π·√( ε_{0}·γ·r^{3} )", "5.4")
b.para("其中 γ 为表面张力，r 为滴半径。图 4 显示：100 μm 水滴的 q_R 约 7 pC，典型感应"
       "充电量 0.3 pC 只占其 4%，工程上非常安全——即偏转法不受充电极限制约，"
       "瓶颈不在这里。", indent=False)
b.figure(f"{F}/fd4_charge.png", "4",
         "充电量的物理边界：感应充电工作点远低于 Rayleigh 极限",
         "Charging limits: induction charging sits far below the Rayleigh "
         "limit", 15.0)

b.h2("5.3　数值仿真：偏移量可测，但简化公式不能直接用",
     "Simulation: Measurable Deflection, but the Simple Formula Fails")
b.para("按典型参数仿真（E = 300 kV/m、板长 15 mm、检测面 40 mm、初速 8 m/s、"
       "充电量按 q ∝ d、100 μm 处 0.3 pC；空气阻力按 Stokes 阻力 × Schiller-Naumann "
       "修正，含重力），结果见图 5：")
b.bullet("偏移量完全可测：100 μm 滴偏移约 1.5 mm，60 μm 滴约 7 mm，150 μm 滴约 "
         "0.6 mm——相机分辨 0.01 mm 很容易，测 y 本身不是问题。")
b.bullet("但简化公式（式 5.1）严重失真：空气阻力使液滴轴向减速、在场区驻留时间变长，"
         "实际偏移比公式值大——100 μm 处偏差约 +40%，50 μm 处达 3 倍。"
         "60 μm 滴飞到 40 mm 检测面时速度已从 8 m/s 掉到约 0.9 m/s。")
b.bullet("结论：反算质量必须用含阻力的数值轨迹模型（本文这种 RK4 积分）或对每个"
         "滴径档做实验标定，而阻力修正本身又依赖滴径——需要迭代，且是系统误差的"
         "重要来源。")
b.figure(f"{F}/fd5_traj.png", "5",
         "带电液滴轨迹仿真：偏移量灵敏度与简化公式的偏差",
         "Charged-droplet trajectory simulation: sensitivity and error of "
         "the ballistic formula", 15.8)

b.h2("5.4　误差预算：做绝对测量不划算", "Error Budget")
b.para("由式 5.2，各测量量的不确定度按下式合成（RSS，另加阻力修正残差）：")
b.equation("δm/m = √( (δq/q)^{2} + (2·δv/v)^{2} + (δE/E)^{2} + (δy/y)^{2} "
           "+ ε_{阻力}^{2} )", "5.5")
b.para_rich([("取乐观的典型值（电荷 3%、速度 1%、场强 1%、偏移 1%、阻力残差 2%），"
              "合成约 4~5%（图 6）；这还没算充电量随电导率、温度的漂移。对比：频闪"
              "成像法约 3%、称重平均法 0.2% 量级。结论一目了然——", ""),
             ("作为绝对测量，偏转法打不过更简单的方案。", "b")], indent=False)
b.figure(f"{F}/fd6_budget.png", "6",
         "偏转法误差预算与三种方案的精度对比",
         "Error budget of the deflection method vs. imaging and gravimetric",
         15.5)

b.h2("5.5　偏转法的正确用法：在线监测器", "The Right Role: an On-line Monitor")
b.para("把偏转法反过来用，它就非常有价值：固定充电电压与偏转场强，此时 y ∝ q/m——"
       "连续监测每一滴的偏移量，滴重漂移、速度漂移、断裂状态变化都会立刻表现为 y 的"
       "变化。传感器只是两块电极加一个相机/PSD，比在线称重简单得多，且天然逐滴、"
       "天然 400~500 Hz 实时。工程配置建议：")
b.bullet("定期用称重平均法（第 3 章）标定，把 y 换算成克数；两次标定之间偏转量作"
         "相对监测。")
b.bullet("同时监测法拉第杯电流：电流恒定而 y 变化 → 滴重/速度变了；电流也变 → "
         "充电或电导率变了。两路信号可以分离“滴变了”还是“充电变了”。")
b.bullet("前提条件复查：液体导电（水基）、工艺允许液滴带电、允许在液滴路径上加装"
         "电极。三者缺一，改用频闪成像法做在线逐滴监测。")

