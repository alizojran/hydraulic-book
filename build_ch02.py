b.h3("2.4.2　传感器/变送器", "Sensors / Transducers")
b.para("如今，液压控制系统通常要求系统响应具有高精度，因而需要精密的装置来测量被控变量或"
       "其他状态变量，如：")
b.bullet("压力；力；位置（角度）；速度（转速）；加速度/减速度；流量。")
b.para("此外需强调的是，所测参数的精度至关重要，因为被控参数的精度永远不可能高于测量装置"
       "的性能。这还涉及所采集测量值传送至电子控制器的频率，而该频率又直接影响系统的响应"
       "与动态行为。由于传感器一般较为昂贵，必须强调：在实际方案中，变送器的数量必须尽量"
       "减少，以使成本尽可能低。")
b.para("下面简要评述最常用的变送器。关于各类传感器工作原理的更多解释，请参阅 Kleman"
       "（1989）和 Norvelle（2000）。")
b.label("2.4.2.1　压力变送器（Pressure Transducers）")
b.para("用于测量压力的装置有（Rohner, 1995；Norvelle, 2000）：", indent=False)
b.bullet("应变片式变送器（非粘贴式、粘贴式、薄膜式、扩散半导体式），非常适合测量静态系统"
         "压力。它们也是唯一能承受高压的可用压力变送器；")
b.bullet("压电式压力变送器。它们通过石英晶体或特种塑料薄膜的机械变形产生电信号。为使"
         "压电效应可用于测量压力，须将变形所得的电荷加以放大和变换。压电压力传感器主要用于"
         "测量快速动态压力，如压力尖峰和脉动压力，不适合长时间的静态压力测量。")
b.para("为测量油缸腔内的压力，压力传感器通常安装在连接阀与油缸的管路中。如果管路过长或过"
       "软（软管），以致出现显著的管路动态特性，则须加以注意：此时每条管路中应安装一个"
       "以上的压力传感器。")
b.para("此外，测量供油压力也是有益的，因为实际应用中常观察到供油压力的波动，它们对伺服"
       "系统起着扰动的作用。油箱压力通常可以忽略，因为它通常远小于所涉及的其他压力。因此，"
       "实际中并不总是需要测量油箱压力。")
b.label("2.4.2.2　力变送器（Force Transducers）")
b.para("对伺服系统起扰动作用的负载力，也应在活塞杆处用力传感器（通常称为称重传感器，"
       "load cell）测量。大多数市售称重传感器只设计用于测量单一方向上的载荷。然而，为降低"
       "成本，大多数实际应用并不设置力测量，而是由压力信号乘以相应的面积间接得到负载力。"
       "关于负载力估计的更多细节，另见 6.10.3 节。原则上，力传感器与压力传感器是相同的。",
       indent=False)
b.label("2.4.2.3　位置变送器（Position Transducers）")
b.para("毫无疑问，最重要的测量信号是活塞（或油缸）的直线位置或位移，以及马达和泵的回转"
       "位置（角度）。用于测量位置或角度的装置有（Walters, 1991；Rohner, 1995）：",
       indent=False)
b.bullet("电位器（直线式、回转式）；")
b.bullet("感应式分压器；")
b.bullet("光电数字传感器；")
b.bullet("非接触式变送器。它们可产生模拟输出信号（即相对某一绝对基准提供无级可变的输出）"
         "或数字输出信号（即提供不带绝对基准的离散增量输出）。非接触式模拟变送器的典型例子"
         "有线性可变位移变送器（LVDT）、旋转可变位移变送器（RVDT）、自整角机和旋转变压器；"
         "数字变送器的例子有编码器和接近传感器。")
b.para("其中，LVDT（如 MTS Temposonics）大概是测量位置最广泛使用的器件。需注意，LVDT 的"
       "线性度使其实际上只适合短行程应用。LVDT 也用于测量伺服阀和比例阀内部的阀芯位置。"
       "对于长行程应用，磁致伸缩器件（MTS Temposonics）很适合（基本上适用于任何可设想的"
       "长度）。其他常用变送器还有衍射光栅（Haidenhain）、线性旋转变压器（Farrand "
       "Inductosyn）和 Sony Magnascale，它们都源自机床工业。")
b.label("2.4.2.4　速度（转速）变送器（Velocity (Speed) Transducers）")
b.para("用于测量速度或角速度的装置有（Kleman, 1989；Walters, 1991；Rohner, 1995）：",
       indent=False)
b.bullet("带永磁直流发电机的转速表（通常简称 tacho）用于测量转速或转数。转速表的工作范围"
         "可以很宽，但有一个下限阈值，限制了最低运行转速。液压马达的转速也可用磁性传感器"
         "（拾波器）和光电编码器测量；")
b.bullet("直线速度可用一根附着在运动负载上的棒状永磁体测量。该永磁体在相邻的管状线圈内"
         "滑动，并在这些线圈中产生与速度相关的电压。")
b.para("此外，实际中通常利用增量式编码器系统的位置信号，通过计算机软件中的微分来估计速度"
       "（见 6.10.1 节），这有助于使传感器成本最小化。")
b.label("2.4.2.5　加速度/减速度变送器（Acceleration/Deceleration Transducers）")
b.para("尽管市场上有加速度传感器，但它们在液压控制系统中并不常用。由于加速度是速度的一阶"
       "时间导数、是位移的二阶时间导数，在运动控制系统中，通过控制速度的变化率即可方便地"
       "处理加速度和减速度（Walters, 1991）。加速度也常以力或压降测量的形式间接测得；见 "
       "6.10.2 节。", indent=False)
b.label("2.4.2.6　流量变送器（Flow Transducers）")
b.para("可使用三类流量变送器（Walters, 1991）：", indent=False)
b.bullet("容积式流量计；压电式文丘里流量计；可变电阻式流量计。")
b.para("其中，容积式流量计和可变电阻式流量计是液压控制应用中最合适的流量变送器。注意，"
       "后一类流量变送器基于对流量的间接测量，即测量安装在待测流量处的某一阻力（即节流孔"
       "限流器）两端的压降。")
b.label("2.4.2.7　温度变送器（Temperature Transducers）")
b.para("温度测量对于准确确定黏度至关重要。在众多测量原理中，液压系统中最常用的有：", indent=False)
