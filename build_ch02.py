b.para("阀是液压系统中通向流体界面的最重要的机械（或电气）环节。")
b.label("2.2.1.1　阀的类型（Valve Types）")
b.para("液压中的阀基本上分为四大类：", indent=False)
b.bullet("（a）压力阀（pressure valve）用于控制执行器的力，并确定和（预）选定某些机器"
         "动作必须在何种压力水平下发生：")
b.bullet("　　·　溢流阀（pressure-relief valve）限制系统允许的最高压力；当达到溢流阀的"
         "压力设定值时，将泵流的一部分或全部导向油箱。溢流阀属于“常闭”阀。")
b.bullet("　　·　减压阀（pressure-reducing valve）限制并维持一个恒定的下游压力（支路"
         "压力），使之小于系统压力，而不受上游主回路压力波动的影响。减压阀属于“常开”阀。")
b.bullet("（b）单向阀（check valve）是一类非常特殊的方向控制阀，它只允许流体单向流动，"
         "而阻止反向流动。它们可分为无负载或弹簧加载的单向阀，以及用于逻辑运算（“或”、"
         "“与”）的单向阀。")
b.bullet("（c）流量阀（flow valve）用于控制流体从液压系统某一部分流向另一部分的流量，"
         "即限制油缸和马达的最高速度，通过控制支路流量限制其可用最大功率，或按比例将"
         "泵流分配/调节到回路的各个分支。")
b.bullet("（d）方向阀（directional valve）用作多极开关。在伺服阀和比例阀出现之前，它们"
         "用于控制执行器运动方向、选择备用控制回路并执行逻辑控制功能。但如今，比例可变"
         "控制使得能够就力、速度和行程位置对执行器进行无级可调、快速可变的设定。")
b.label("2.2.1.2　从电磁阀到伺服阀（From Solenoid-valves to Servo-valves）")
b.para("用于流体动力控制的最简单的阀是电磁阀（solenoid-valve）。它只是一种开关阀，即"
       "要么被激励、要么不被激励——全开或全闭，没有中间位置。近一个世纪以来，电磁阀一直"
       "用于流体动力领域，其原始概念几乎没有大的变化（Norvelle, 2000）。在认识到采用电磁阀"
       "的液压系统在性能上的巨大局限后，自 20 世纪 50 年代起，人们发展出了集成伺服阀的"
       "控制概念（从而出现了伺服液压系统或伺服机构）。伺服阀（servo-valve）是响应更快的"
       "方向、压力和流量控制阀，常用于闭环控制方案，以实现现代机器所要求的高度精密的性能"
       "（就高频响应而言）。伺服阀也许最早、最常见的应用是在航空航天飞行器中，尤其是主"
       "飞行操纵系统中。如今，伺服阀已广泛应用于采矿、轧制、农业、运输和航运等众多其他"
       "工业领域。", indent=False)
b.label("2.2.1.3　从伺服阀到“精制”比例阀（From Servo-valves to “Refined” Proportional Valves）")
b.para("长期以来，简单的开关阀与高度精密的伺服阀之间一直存在巨大的鸿沟。随着 20 世纪 70 "
       "年代比例（控制）阀的出现，这一状况发生了改变。如今，主要的液压元件制造商都提供"
       "大量比例阀。", indent=False)
b.para("比例阀与伺服阀有一个共同的主要概念：通常其输出变量——即阀芯位置（方向阀）、压力"
       "（压力阀）或流量（流量阀）——与输入信号成比例。这种输入信号可以是手动、机械、气动"
       "或电气的。现代伺服阀和比例阀系统通常使用低功率的电模拟或数字信号。")
b.para("由于伺服阀是高度精密的控制阀，常用于闭环控制方案，因此必须具有非常精确的计量"
       "尺寸，从而往往涉及高昂的安装与采购成本。即使是最轻微的流体污染，也可能导致伺服阀"
       "中精密的机构失灵。")
b.para("比例阀能够用于方向、压力和流量控制，并能以电子方式将其调整到工作范围内无穷多个"
       "位置，这使它们在广泛的液压应用中极为有用且广受欢迎。比例阀的基本工作原理是利用"
       "比例电磁铁（proportional solenoid）将阀芯移动到所需位置。“非精制”比例阀通常较为"
       "便宜，性能要求较低，如较大的滞环和死区，主要用于开环应用。伺服阀与比例阀的性能"
       "和应用领域的概要见表 2.1 和表 2.2。")
b.para("近年来，由于比例电磁铁的进一步发展（加入阀芯位置反馈，改进阀芯与电子线路的设计，"
       "在精度、滞环、死区等方面的性能提升），如今也有了高度精密的比例阀——尽管输入功率"
       "较高，却表现出与伺服阀相似的非常好的动态特性。这类比例阀被称为“控制阀”或“精制”"
       "比例阀，也可用于闭环控制。于是，“伺服阀”与“比例阀”的定义及二者的区分，已变得越来越"
       "模糊和重叠（自 20 世纪 80 年代起）。甚至在许多现代工业应用（如移动液压）中，将两级"
       "伺服阀与比例阀（作为主级）相结合也并不少见，因为这类阀既能满足高技术要求，又同时"
       "具有鲁棒性（Will 等, 1999）。")
b.para("伺服阀（和比例阀）大致可分为单级（single-stage）或多级（如两级、三级）。单级"
       "伺服阀包含一个力矩马达，通过直接连接来定位（通常为四通的）阀芯。单级阀简单、便宜，"
       "但由于力矩马达功率能力有限，其流量能力也有限（最大约 20 dm³/min）。")
b.para("多级伺服阀具有一个或两个液压前置放大器，将力矩马达的力输出大幅放大到足以克服可观"
       "的流动力、摩擦力以及由加速或振动产生的力的水平。挡板阀、射流管阀和滑阀可用作先导"
       "（或主控）级阀，而第二（或从动）级阀几乎无一例外地采用滑阀型。")

