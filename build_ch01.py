b.h2("1.1　液压系统的历史回顾与研究动因",
     "Historical View and Motivation for Hydraulic Systems")
b.para("Maskrey 和 Thayer（1978）以及 Backe 和 Murrenhoff（1994）曾对液压机构的历史"
       "做过简要而饶有趣味的梳理。下文概述后者的工作，并建议读者参阅这两篇文献以获得更"
       "完整的论述。")
b.para("流体动力（fluid power）技术可以追溯到约公元前 250 年亚历山大城发明家克特西比乌斯"
       "（Ktesbios）发明的水钟，但真正使液压技术变得重要的，是帕斯卡（Pascal）的工作——"
       "他于 1663 年提出了液压机（hydraulic press）原理。液压机（以水为工作介质）的首次"
       "工业应用，则是后来由约瑟夫·布拉默（Josef Bramah，1749—1814）于 1795 年在伦敦"
       "完成的。")
b.para("继詹姆斯·瓦特（James Watt，1736—1819）发明蒸汽机之后，静液压（hydrostatic）机械"
       "以加压水管网的形式，在英国被广泛用于能量交换。人们用蒸汽机驱动的泵产生压力水，"
       "再以压力水驱动活塞，进而带动加工机械（如各类磨机）。")
b.para("19 世纪下半叶，W. G. 阿姆斯特朗（W. G. Armstrong，1810—1900）研制了许多静液压"
       "机械与装置，主要用于造船业（如绞盘、起重千斤顶）。其中一些控制装置至今仍与现今"
       "使用的相似。")
b.para("此后，流体动力技术主要自 20 世纪初开始发展。第一代液压驱动由某种流量控制装置"
       "以开环（open loop）方式驱动液压执行器构成，因此常见应用仅限于液压机、千斤顶和"
       "卷扬机。")
b.para("流体动力之所以广受欢迎，其主要优点在于：一方面所输出的力或力矩较大，另一方面"
       "执行器的重量和体积却较小，二者比值优良。在许多应用中，这使得所谓的直接驱动"
       "（direct drive）结构成为可能，从而避免使用易磨损的齿轮箱。各类移动机械中的液压"
       "驱动与传动便是例证。")
b.para("液压驱动最初用于开环作动，而第二次世界大战之后，能够实现精确闭环（closed loop）"
       "运动控制的伺服控制（servo-control）技术的应用日益增多。Blackburn 等人（1960）的"
       "贡献进一步推动了液压伺服技术的发展，开辟了至今仍见于工业界的广泛应用领域。液压"
       "伺服系统被用于以下场合：")
b.bullet("需要较大的力或力矩之处（工业压力机，移动式起重、挖掘、物料搬运设备等）；")
b.bullet("需要对阻性负载作出快速、刚硬响应之处（机床驱动、飞行模拟器、轧机等）；")
b.bullet("需要对响应进行精确控制之处（飞机操纵面、机床滑台、工业机器人等）；")
b.bullet("必须以人工方式控制涉及较大力的运动之处（重型机械、飞机操纵、汽车动力转向等）；")
b.bullet("作为复杂自动控制场合中的末级执行子系统（电液飞行模拟器、工业机器人、疲劳及其他"
         "可编程试验台、剧场舞台控制等）。")
b.para("相比其他类型的控制（如电动机），液压控制系统具有诸多优点，其中包括"
       "（Merritt, 1967；Bauer, 1998；Will 等, 1999）：")
b.bullet("液压系统能产生更大的力/力矩，并具有更高的负载刚度；")
b.bullet("液压油本身是极好的润滑剂，可避免磨损；")
b.bullet("液压执行器响应速度更快，能够迅速启动、停止和换向；")
b.bullet("液压系统可在多种工况下运行（连续、间歇、换向、堵转）；")
b.bullet("既有直线执行器也有回转执行器，进一步增强了液压动力元件的灵活性；")
b.bullet("过载保护简单易行；")
b.bullet("可获得体积更小、重量更轻、结构紧凑且元件寿命长的系统。")
b.para("除上述优点外，流体动力显然也存在一些缺点，其中包括"
       "（Merritt, 1967；Bauer, 1998；Will 等, 1999）：")
b.bullet("由于允许的公差很小，液压元件成本高昂；")
b.bullet("若液压系统在点火源附近使用，存在火灾与爆炸危险；")
b.bullet("油液的脏污与污染难以完全避免，可能导致阀和执行器堵塞，以及性能的永久性下降"
         "和/或失效。受污染的油液实际上是液压控制故障的首要根源——在液压控制中，"
         "“清洁的油液”与“可靠性”是同义词；")
b.bullet("液压系统的动态特性高度非线性，相对难以控制；")
b.bullet("液压声响或噪声：噪声问题在今天尤为关键——更高的功率密度，加上高工作压力和"
         "更轻的元件，导致噪声水平上升；与此同时，许多国家和应用场合的规范与标准都要求"
         "进行噪声防护（以避免健康危害）。")

