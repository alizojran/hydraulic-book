b.bullet("液压伺服系统及其部件的结构与运行（功能）细节不在本书范围之内。读者可参阅标准"
         "教材，如 Blackburn 等（1960）、Merritt（1967）、Ivantysyn 和 Ivantysynova"
         "（1993）、Backe 和 Murrenhoff（1994）、Findeisen 和 Findeisen（1994）、"
         "Rohner（1995）、Merkle 等（1997a, 1997b）、Will 等（1999）。")
b.bullet("以合理确定系统部件尺寸为含义的液压伺服系统“系统设计”问题，本书亦不涉及。这一"
         "问题已为人熟知，并已由 Merritt（1967）、Viersma（1980）、Anderson（1988）和"
         "Walters（1991）广泛讨论。")
b.para("需要强调的是，从伺服控制的角度看，良好的系统设计应被视为通过闭环控制获得良好"
       "性能的前提。")
b.para("过程设计与控制之间的关系，可以用 Ziegler 和 Nichols（1943）一篇论文中的话来"
       "简练地概括：“在应用自动控制器时，重要的是要认识到，控制器与过程构成一个整体；"
       "所得结果的功过，二者各占其半。一个糟糕的控制器，往往也能在易于控制的过程上表现"
       "得令人接受；而制造得最精良的控制器，若用于一个设计得很糟糕的过程，也可能无法交出"
       "所期望的性能。诚然，在设计糟糕的过程上，先进控制器能比老式控制器勉强取得更好的"
       "结果，但在这类过程上存在一个明确的极限点，仪表所能逼近的，也就到此为止，且达不到"
       "完美。”")

